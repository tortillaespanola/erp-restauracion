-- ============================================================
-- 5. Registro de incidencias — triggers AFTER diferidos (mismo
--    momento de evaluación que los de validación), uno por tabla
--    de consumo, cada uno decide en cuál de las dos tablas de
--    incidencias insertar según el tipo de origen de esa línea.
-- ============================================================

create or replace function public.registrar_incidencia_stock_negativo_consumo()
returns trigger
language plpgsql
as $$
declare
  v_tipo_produccion text;
  v_disponible numeric;
begin
  select tipo_produccion into v_tipo_produccion from producciones_semielaborado where id = NEW.produccion_id;
  if v_tipo_produccion is distinct from 'evento_directo' then
    return NEW;
  end if;

  if NEW.entrada_material_id is not null then
    select em.cantidad
      - coalesce((select sum(cantidad) from consumo_produccion where entrada_material_id = NEW.entrada_material_id), 0)
      - coalesce((select sum(cantidad) from consumo_produccion_pf where entrada_material_id = NEW.entrada_material_id), 0)
      + coalesce((select sum(cantidad) from ajustes_articulo where entrada_material_id = NEW.entrada_material_id), 0)
    into v_disponible
    from entrada_material em
    where em.id = NEW.entrada_material_id;

    if v_disponible < 0 then
      insert into incidencias_stock_articulo (entrada_material_id, consumo_produccion_id, cantidad_negativa)
      values (NEW.entrada_material_id, NEW.id, abs(v_disponible));
    end if;
  else
    select p.cantidad_producida
      - coalesce((select sum(cantidad) from consumo_produccion where produccion_origen_id = NEW.produccion_origen_id), 0)
      - coalesce((select sum(cantidad) from consumo_produccion_pf where produccion_origen_id = NEW.produccion_origen_id), 0)
      + coalesce((select sum(cantidad) from ajustes_semielaborado where produccion_id = NEW.produccion_origen_id), 0)
    into v_disponible
    from producciones_semielaborado p
    where p.id = NEW.produccion_origen_id;

    if v_disponible < 0 then
      insert into incidencias_stock_semielaborado (produccion_semielaborado_id, consumo_produccion_id, cantidad_negativa)
      values (NEW.produccion_origen_id, NEW.id, abs(v_disponible));
    end if;
  end if;

  return NEW;
end;
$$;

create constraint trigger trg_registrar_incidencia_stock_negativo_consumo
after insert or update on consumo_produccion
deferrable initially deferred
for each row execute function registrar_incidencia_stock_negativo_consumo();

